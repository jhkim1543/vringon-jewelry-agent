// 조사 결과를 쓸 때 모델에게 건네는 언어 이름. 화면 언어와 같은 값을 쓴다.
export const LANG_NAME: Record<Lang, string> = {
  en: 'English', ko: 'Korean (한국어)', ja: 'Japanese (日本語)',
}

const KEY = 'vringon.lang'

function initial(): Lang {
  try {
    // 호스트(VRINGON)가 언어를 정해 주면 그걸 따른다 · 순환 임포트를 피해 주소를 직접 읽는다
    const q = new URLSearchParams(location.search).get('lang')
    if (q === 'ko' || q === 'en' || q === 'ja') return q
    const saved = localStorage.getItem(KEY)
    if (saved === 'ko' || saved === 'en' || saved === 'ja') return saved
    const nav = navigator.language?.toLowerCase() ?? ''
    if (nav.startsWith('ko')) return 'ko'
    if (nav.startsWith('ja')) return 'ja'
    return 'en'
  } catch {
    return 'en'
  }
}

let lang: Lang = initial()
// html lang 도 처음부터 맞춘다 (스크린리더·글꼴 폴백이 이걸 본다)
try { document.documentElement.lang = lang } catch { /* 무시 */ }
const listeners = new Set<() => void>()

export function getLang(): Lang { return lang }

export function setLang(l: Lang, opts?: { fromHost?: boolean }) {
  if (l === lang) return
  lang = l
  // 호스트(VRINGON)가 정해 준 언어는 이 앱의 저장소에 남기지 않는다 —
  // 다음에 이 앱을 따로 열었을 때 남의 선택이 따라오면 안 된다.
  if (!opts?.fromHost) { try { localStorage.setItem(KEY, l) } catch { /* 무시 */ } }
  document.documentElement.lang = l
  listeners.forEach(fn => fn())
}

export function useLang(): Lang {
  return useSyncExternalStore(
    (fn) => { listeners.add(fn); return () => listeners.delete(fn) },
    () => lang,
    () => lang,
  )
}

/** 영문 원문 → 현재 언어. 사전에 없으면 원문 그대로 나가므로 화면이 깨지지 않는다. */
export function t(s: string): string {
  if (lang === 'en') return s
  const dict = lang === 'ja' ? JA : KO
  return dict[s] ?? s
}

/** 치환이 있는 문장. t('{n} designs') 처럼 쓰고 vars로 값을 넣는다. */
export function tf(s: string, vars: Record<string, string | number>): string {
  let out = t(s)
  for (const k of Object.keys(vars)) out = out.split(`{${k}}`).join(String(vars[k]))
  return out
}

